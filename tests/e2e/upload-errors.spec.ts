import { existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { ERROR_CATALOGUE } from '../../supabase/functions/_shared/pure/error-catalogue';
import { admin, FIXTURES } from '../integration/helpers';
import { expect, test } from './fixtures';

// Spec 12 §12.8 upload-errors.spec: each bad PDF shows its catalogue message and creates no row.
const CASES = [
  ['scanned.pdf', 'SCANNED_PDF'],
  ['pages-21.pdf', 'TOO_MANY_PAGES'],
  ['encrypted.pdf', 'PDF_PASSWORD_PROTECTED'],
  ['large-11mb.pdf', 'FILE_TOO_LARGE'], // rejected in the browser before any upload
] as const;

for (const [file, code] of CASES) {
  test(`${file} → "${ERROR_CATALOGUE[code].message}"`, async ({ page, signedIn }) => {
    const path = resolve(FIXTURES, file);
    test.skip(!existsSync(path), `${file} is generated by \`npm run fixtures\` (not committed)`);

    await page.goto('/contracts/new');
    await page.getByRole('radio', { name: /^NDA/ }).check();
    await page.locator('input[type="file"]').setInputFiles(path);
    await expect(page.getByText(ERROR_CATALOGUE[code].message)).toBeVisible({ timeout: 30_000 });
    await expect(page.getByRole('button', { name: 'Process Contract' })).toBeDisabled();

    const { count } = await admin.from('contracts').select('id', { count: 'exact', head: true }).eq('user_id', signedIn.id);
    expect(count).toBe(0);
  });
}
